import {request} from './client.js';
export const loadAll=async()=>Object.fromEntries(await Promise.all(['sources','periods','policies','runs','schedules','deliveries','audits','errata'].map(async k=>[k,await request('/'+k)])));
export const saveSource=(data,id)=>request('/sources'+(id?'/'+id:''),id?'PUT':'POST',{data});
export const savePolicy=data=>request('/policies','POST',{data});
export const submitRun=data=>request('/runs','POST',data);
export const approveRun=(id,note)=>request('/runs/'+id+'/approve','POST',{note});
export const loadErrata=id=>request('/errata/'+id);
export const createErrata=data=>request('/errata','POST',data);
export const retryErrata=id=>request('/errata/'+id+'/retry','POST',{});
export const reviewErrata=(id,note)=>request('/errata/'+id+'/review','POST',{note});
export const switchErrata=id=>request('/errata/'+id+'/switch','POST',{});
